from decimal import Decimal
from unittest.mock import patch

import pytest
from pydantic_ai import ModelResponse, TextPart, models
from pydantic_ai.models.function import FunctionModel
from sqlalchemy import select
from sqlalchemy.ext.asyncio import async_sessionmaker

from app.models.enums import ExtractionStatus, SelectorProfileStatus
from app.models.product import Product
from app.models.selector_profile import SelectorProfile
from app.schemas.scraper import ScrapedResult
from app.services import selector_profile_service
from app.services.llm import client as llm_client
