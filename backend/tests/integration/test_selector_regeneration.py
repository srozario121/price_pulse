"""Integration tests for the selector regeneration Celery task (Item 16).

Arrange-Act-Assert throughout. Runs against the Postgres testcontainer because
the task creates ``SelectorProfile`` rows with generated ids — SQLite does not
autoincrement a ``BigInteger`` primary key. The task body is invoked directly
with ``AsyncSessionLocal`` pointed at the test engine, so no broker or worker is
involved; the LLM is a Pydantic AI ``FunctionModel`` and no provider is contacted.

The behavioural contract under test: the task never raises, never retries, and
every non-promotion outcome is accounted for — either as a counted attempt
against the host's budget, or (for "generation disabled") explicitly *not*
counted, so a deployment with no key does not park every host as failed.
"""

from __future__ import annotations

