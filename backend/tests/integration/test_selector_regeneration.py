from app.services.selector_generation import validate_selector
from app.tasks import selector as selector_task

models.ALLOW_MODEL_REQUESTS = False

pytestmark = pytest.mark.integration

_HOST = "shop.example.com"
_HTML = (
    "<html><body><h1>Widget</h1>"
    '<div id="buybox"><span class="pdp-price">£129.50</span></div></body></html>'
)


def _scraped(status: ExtractionStatus, html: str = _HTML) -> ScrapedResult:
    return ScrapedResult(
        url=f"https://{_HOST}/p/1",
        html=html,
        html_hash="hash",
        price=None,
        currency=None,
        scraped_at=datetime.now(UTC),
        extraction_status=status,
    )


def _model(payload: str) -> FunctionModel:
    """A model that always replies with *payload* as the structured output."""

    def respond(messages, info):  # noqa: ANN001, ARG001
        return ModelResponse(parts=[TextPart(content=payload)])

    return FunctionModel(respond)


def _exploding_model(message: str) -> FunctionModel:
    def explode(messages, info):  # noqa: ANN001, ARG001
        raise RuntimeError(message)

    return FunctionModel(explode)


def _forbidden_model() -> FunctionModel:
    def forbidden(messages, info):  # noqa: ANN001, ARG001
        raise AssertionError("the LLM must not be called on this path")

    return FunctionModel(forbidden)


